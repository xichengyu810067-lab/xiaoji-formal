'use strict';

// Writes the last release's offline health check of the public slash commands into the website
// (website/statusHealthCheck.js), for the status page to show only when it has no live data at all.
//
// The health check (run by hand before a release) leaves data/health/public-commands.json:
//   { checkedAt: ISO time, commands: [{ path: '/bank fixed-create', status: 'pass' | 'fail' | 'skip' }] }
// It runs every command in a fake Discord, so it says whether this release's code works, not whether the live bot does.
// Only the paths of the public command list (src/platform/publicCommandStatus.js) are kept, and only pass or fail:
// a name outside that list never reaches the website. Run it before a release, after the health check:
//   node scripts/build-status-health-check.js [--from data/health/public-commands.json]

const fs = require('node:fs');
const path = require('node:path');
const { listPublicCommands } = require('../src/platform/publicCommandStatus');
const packageJson = require('../package.json');

const ROOT = path.resolve(__dirname, '..');
const DEFAULT_SOURCE = path.join(ROOT, 'data', 'health', 'public-commands.json');
const TARGET = path.join(ROOT, 'website', 'statusHealthCheck.js');
const STATUSES = new Set(['pass', 'fail']);

function parseCheckedAt(value) {
  if (typeof value !== 'string') return null;
  const time = Date.parse(value);
  return Number.isFinite(time) ? new Date(time).toISOString() : null;
}

// { checkedAt, version, commands: { name: { status?, subcommands: { sub: status } } } } from the health check output.
function buildHealthCheck(report, { commands = listPublicCommands(), version = packageJson.version } = {}) {
  const checkedAt = parseCheckedAt(report?.checkedAt);
  if (!checkedAt) throw new Error('The health check has no valid checkedAt time.');
  const known = new Map(commands.map((command) => [command.name, new Set(command.subcommands)]));
  const result = {};
  let dropped = 0;
  for (const entry of Array.isArray(report?.commands) ? report.commands : []) {
    const match = /^\/([a-z0-9-]{1,32})(?: ([a-z0-9-]{1,32}))?$/u.exec(typeof entry?.path === 'string' ? entry.path : '');
    const status = entry?.status;
    if (!match || !known.has(match[1]) || (match[2] && !known.get(match[1]).has(match[2]))) {
      dropped += 1;
      continue;
    }
    if (!STATUSES.has(status)) continue;
    const command = result[match[1]] ||= { subcommands: {} };
    if (match[2]) command.subcommands[match[2]] = status;
    else command.status = status;
  }
  // Commands in catalog order, so the file only changes when a result does.
  const ordered = {};
  for (const command of commands) if (result[command.name]) ordered[command.name] = result[command.name];
  return { checkedAt, version, commands: ordered, dropped };
}

function render(healthCheck) {
  const data = healthCheck
    ? JSON.stringify({ checkedAt: healthCheck.checkedAt, version: healthCheck.version, commands: healthCheck.commands }, null, 2)
    : 'null';
  return [
    '// Generated by scripts/build-status-health-check.js from the last release\'s offline health check. Do not edit by hand.',
    '// The status page shows it only when it has no live command statuses at all. null: no health check was recorded.',
    '(function exposeStatusHealthCheck(root) {',
    `  const data = ${data.replace(/\n/gu, '\n  ')};`,
    "  if (typeof module === 'object' && module.exports) module.exports = data;",
    '  else root.XiaojiStatusHealthCheck = data;',
    "})(typeof globalThis === 'object' ? globalThis : this);",
    '',
  ].join('\n');
}

if (require.main === module) {
  const index = process.argv.indexOf('--from');
  const source = index > 0 ? path.resolve(process.argv[index + 1]) : DEFAULT_SOURCE;
  const healthCheck = buildHealthCheck(JSON.parse(fs.readFileSync(source, 'utf8')));
  fs.writeFileSync(TARGET, render(healthCheck), 'utf8');
  const count = Object.values(healthCheck.commands).reduce((sum, command) => sum + ('status' in command ? 1 : 0) + Object.keys(command.subcommands).length, 0);
  console.log(`Wrote website/statusHealthCheck.js: ${count} paths checked at ${healthCheck.checkedAt}${healthCheck.dropped ? `, ${healthCheck.dropped} unknown paths dropped` : ''}.`);
}

module.exports = { TARGET, buildHealthCheck, render };
