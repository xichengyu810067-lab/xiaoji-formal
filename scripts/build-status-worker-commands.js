'use strict';

// Writes the public slash commands and subcommands the status worker accepts in a snapshot
// (cloudflare/status-worker/src/publicCommands.mjs) from src/platform/catalogs/commandCatalog.js, through the same list the bot
// publishes (src/platform/publicCommandStatus.js). The worker is deployed on its own, so it carries its own copy.
// test/publicCommandStatus.test.js fails when the copy falls behind: run node scripts/build-status-worker-commands.js.

const fs = require('node:fs');
const path = require('node:path');
const { listPublicCommands } = require('../src/platform/publicCommandStatus');

const TARGET = path.resolve(__dirname, '..', 'cloudflare', 'status-worker', 'src', 'publicCommands.mjs');

function render() {
  const lines = listPublicCommands().map(({ name, subcommands }) => `  ${JSON.stringify(name)}: ${JSON.stringify(subcommands)},`);
  return [
    '// Generated by scripts/build-status-worker-commands.js from src/platform/catalogs/commandCatalog.js. Do not edit by hand.',
    '// The public slash commands and their subcommands a status snapshot may list; anything else is dropped.',
    'export const PUBLIC_COMMANDS = Object.freeze({',
    ...lines,
    '});',
    '',
  ].join('\n');
}

if (require.main === module) {
  fs.writeFileSync(TARGET, render(), 'utf8');
  console.log(`Wrote ${path.relative(process.cwd(), TARGET)}.`);
}

module.exports = { TARGET, render };
