// Written forms that players type for the same character, such as 台灣 and 臺灣, or 周末 and 週末. The comparison
// key of a word (wordKey) replaces every listed form with the character it maps to, so such spellings are one word.
// That character is only a fixed representative of the group, not the preferred spelling and not always the more
// common one (more headwords use 周 than 週, and the key still uses 週). Stored words keep the spelling that was
// typed; only matching uses the key. Characters that have words of their own, such as 里 and 裡, 后 and 後, or
// 妳 and 你, are not folded.
//
// Folding has a price that is accepted on purpose. 檯 is folded into 臺 because that is what makes 台燈 and 吧台
// words (the dictionary lists 檯燈 and 吧檯, not 臺燈 and 吧臺). With 台 it makes three pairs of headwords share a
// key although they are not the same word in everyday use: 轉檯 and 轉臺, 上檯 and 上臺, 天台 and 天臺. After one
// of a pair has been used in a round the other counts as used. test/wordChainCoverage.test.js pins every group of
// words that share a key, so a pair that is added has to be reviewed.
const variantForms = Object.freeze({
  台: '臺', 檯: '臺', 周: '週', 秘: '祕', 温: '溫', 裏: '裡', 爲: '為', 着: '著',
  衆: '眾', 峯: '峰', 羣: '群', 啓: '啟', 喫: '吃', 綫: '線', 証: '證', 户: '戶',
  脚: '腳', 麪: '麵', 恒: '恆', 污: '汙', 兇: '凶', 蹟: '跡', 嚐: '嘗', 勳: '勛',
  佈: '布', 濕: '溼', 曬: '晒', 樑: '梁', 雇: '僱',
});
const variantFormMap = new Map(Object.entries(variantForms));
const variantFormPattern = new RegExp(`[${Object.keys(variantForms).join('')}]`, 'u');

// The comparison key of a word or a single character. A word without a listed form is its own key.
function wordKey(word) {
  const text = String(word);
  if (!variantFormPattern.test(text)) return text;
  let key = '';
  for (const character of text) key += variantFormMap.get(character) ?? character;
  return key;
}

const hash = (value) => crypto.createHash('sha256').update(value).digest('hex');

function readRequiredAsset(directory, fileName) {
  try {
    return fs.readFileSync(path.join(directory, fileName));
  } catch (_error) {
    throw new WordChainLexiconError('LEXICON_ASSET_UNAVAILABLE', 'Word-chain lexicon assets are unavailable.');
  }
}

function loadCorpusAssets(directory = path.resolve(__dirname, '../../assets/word-chain')) {
  let loadedMetadata;
  try {
    loadedMetadata = JSON.parse(readRequiredAsset(directory, metadataFile).toString('utf8'));
  } catch (error) {
    if (error instanceof WordChainLexiconError) throw error;
    throw new WordChainLexiconError('LEXICON_METADATA_INVALID', 'Word-chain lexicon metadata is invalid.');
  }

  const indexBytes = readRequiredAsset(directory, indexFile);
  const usageBytes = readRequiredAsset(directory, usageFile);
  const noticeText = readRequiredAsset(directory, noticeFile).toString('utf8');
  if (
    loadedMetadata.sourceVersion !== '2015_20260625' ||
    loadedMetadata.indexFile !== indexFile ||
    loadedMetadata.usageInstructionsFile !== usageFile ||
    loadedMetadata.license !== 'CC BY-ND 3.0 TW' ||
    hash(indexBytes) !== loadedMetadata.indexSha256 ||
    hash(usageBytes) !== loadedMetadata.usageInstructionsSha256 ||
    hash(Buffer.from(noticeText, 'utf8')) !== noticeSha256 ||
    !noticeText.includes('2015_20260625') ||
    !noticeText.includes('創用 CC')
  ) {
    throw new WordChainLexiconError('LEXICON_INTEGRITY_FAILED', 'Word-chain lexicon assets failed integrity verification.');
  }

  return Object.freeze({
    metadata: Object.freeze(loadedMetadata),
    moeWords: Object.freeze(indexBytes.toString('utf8').trimEnd().split('\n')),
  });
}

const loadedAssets = loadCorpusAssets();
const metadata = loadedAssets.metadata;
const moeWords = loadedAssets.moeWords;
const legacyWordSet = new Set(legacyWords);
const words = Object.freeze([
  ...legacyWords,
  ...moeWords.filter((word) => !legacyWordSet.has(word)),
  ...supplementWords,
]);
const wordSet = new Set(words);

// wordSet holds the words as written; keySet holds their comparison keys, which is what matching uses, and
// byInitial indexes the words by the key of their first character.
function createCorpusIndex(corpusWords) {
  const keySet = new Set();
  const byInitial = new Map();
  for (const word of corpusWords) {
    keySet.add(wordKey(word));
    const initial = wordKey(Array.from(word)[0]);
    if (!byInitial.has(initial)) byInitial.set(initial, []);
    byInitial.get(initial).push(word);
  }
  for (const successors of byInitial.values()) Object.freeze(successors);
  return { words: corpusWords, wordSet: new Set(corpusWords), keySet, byInitial };
}

const corpora = new Map([
  [legacyCorpusVersion, createCorpusIndex(legacyWords)],
  [corpusVersion, createCorpusIndex(words)],
]);

function getCorpus(version = corpusVersion) {
  const corpus = corpora.get(version);
  if (!corpus) throw new Error(`Unknown word-chain corpus version: ${version}`);
  return corpus;
}

// Is the word in the corpus, in any of its written forms?
function hasWord(word, version = corpusVersion) {
  return getCorpus(version).keySet.has(wordKey(word));
}

// The words that may follow: those whose first character has the same key as the last character of the word.
function getSuccessors(word, version = corpusVersion) {
  const requiredInitial = wordKey(Array.from(word).at(-1));
  return getCorpus(version).byInitial.get(requiredInitial) || [];
}

function assertCorpusInvariant() {
  const baseKeys = new Set([...legacyWords, ...moeWords].map(wordKey));
  const supplementKeys = supplementWords.map(wordKey);
  if (
    legacyWords.length < 150 || legacyWordSet.size !== legacyWords.length ||
    moeWords.length !== metadata.uniqueHeadwords || new Set(moeWords).size !== moeWords.length ||
    supplementWords.length === 0 || new Set(supplementKeys).size !== supplementWords.length ||
    supplementWords.some((word) => legacyWordSet.has(word)) || supplementKeys.some((key) => baseKeys.has(key)) ||
    wordSet.size !== words.length ||
    !words.every((word) => /^\p{Script=Han}{2,6}$/u.test(word))
  ) {
    throw new Error('Word-chain corpus invariant failed.');
  }
}

