const SAFE_LINE_PATTERN = /\[TEST_CONTROL\]\s+code=([A-Z0-9_]+)\s+operation=([a-z0-9_]+)/;

function createSessionId() {
  return crypto.randomBytes(16).toString('hex');
}

function isSessionId(value) {
  return SESSION_PATTERN.test(String(value || ''));
}

function isStartupNonce(value) {
  return STARTUP_NONCE_PATTERN.test(String(value || ''));
}

function isClosedStartupFreshnessMessage(value) {
  if (!STARTUP_FRESHNESS_TYPES.has(value.type)) return true;
  const keys = Object.keys(value).sort();
  return keys.length === 4 && keys.join(',') === 'nonce,session,type,version' &&
    isStartupNonce(value.nonce);
}

function createControlMessage(type, session, details = {}) {
  if (!CONTROL_TYPES.has(type) || !isSessionId(session)) return null;
  const message = { version: PROTOCOL_VERSION, type, session, ...details };
  return isClosedStartupFreshnessMessage(message) ? Object.freeze(message) : null;
}

function isControlMessage(value, { type, session } = {}) {
  if (!value || typeof value !== 'object' || Array.isArray(value) || value.version !== PROTOCOL_VERSION ||
      !CONTROL_TYPES.has(value.type) || !isSessionId(value.session)) return false;
  if (!isClosedStartupFreshnessMessage(value)) return false;
  if (type && value.type !== type) return false;
  if (session && value.session !== session) return false;
  if (value.reason !== undefined && !STOP_REASONS.has(value.reason)) return false;
  if (value.outcome !== undefined && !EXIT_OUTCOMES.has(value.outcome)) return false;
  if (value.sequence !== undefined && (!Number.isSafeInteger(value.sequence) || value.sequence < 0)) return false;
  return true;
}

function safeControlLine(code, operation) {
  const safeCode = SAFE_CODES.has(code) || ROUTE_DIAGNOSTIC_PATTERN.test(code) ? code : null;
  if (!safeCode || !SAFE_OPERATIONS.has(operation) ||
      (operation === 'startup_diagnostic' && !STARTUP_DIAGNOSTIC_CODES.has(code))) return null;
  return `[TEST_CONTROL] code=${safeCode} operation=${operation}`;
}

function parseSafeControlLine(value) {
  const match = SAFE_LINE_PATTERN.exec(String(value || ''));
  return match ? safeControlLine(match[1], match[2]) : null;
}

function createBoundedLineDrain({
  stream,
  streamName,
  emitLine,
  acceptLine = () => true,
  maxLineBytes = 2048,
  maxTotalBytes = 64 * 1024,
}) {
  const decoder = new StringDecoder('utf8');
  let buffered = '';
  let totalBytes = 0;
  let suppressionReported = false;

  function suppress() {
    if (suppressionReported) return;
    suppressionReported = true;
    emitLine(safeControlLine(
      streamName === 'stdout' ? 'TEST_CHILD_STDOUT_SUPPRESSED' : 'TEST_CHILD_STDERR_SUPPRESSED',
      'launcher'
    ));
  }

  function inspect(line) {
    if (Buffer.byteLength(line, 'utf8') > maxLineBytes) return suppress();
    const safe = parseSafeControlLine(line);
    if (safe && acceptLine(safe)) emitLine(safe);
    else if (line.trim()) suppress();
  }

  function onData(chunk) {
    totalBytes += chunk.length;
    if (totalBytes > maxTotalBytes) {
      buffered = '';
      suppress();
      return;
    }
    buffered += decoder.write(chunk);
    if (Buffer.byteLength(buffered, 'utf8') > maxLineBytes * 2) {
      buffered = '';
      suppress();
      return;
    }
    const lines = buffered.split(/\r?\n/u);
    buffered = lines.pop() || '';
    for (const line of lines) inspect(line);
  }

  function onEnd() {
    buffered += decoder.end();
    if (buffered) inspect(buffered);
    buffered = '';
  }

  stream.on('data', onData);
  stream.on('end', onEnd);
  return Object.freeze({
    close() {
      stream.off('data', onData);
      stream.off('end', onEnd);
      buffered = '';
    },
  });
}

